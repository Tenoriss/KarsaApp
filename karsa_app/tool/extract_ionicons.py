#!/usr/bin/env python3
"""Extract Ionicons.ttf and generate karsa_icons.dart from @expo/vector-icons@15.0.2."""

import io
import json
import os
import tarfile
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF_OUT = os.path.join(ROOT, "assets", "fonts", "Ionicons.ttf")
DART_OUT = os.path.join(ROOT, "lib", "core", "widgets", "karsa_icons.dart")

ICON_NAMES = [
    "chevron-back",
    "chevron-forward",
    "sunny-outline",
    "moon-outline",
    "notifications-outline",
    "people",
    "checkmark-circle",
    "pencil",
    "book",
    "refresh-outline",
    "grid",
    "megaphone",
    "person-outline",
    "book-outline",
    "shield-checkmark-outline",
    "help-circle-outline",
    "checkmark",
    "albums",
    "checkmark-done",
    "card-outline",
    "lock-closed-outline",
    "eye-off-outline",
    "eye-outline",
    "home",
    "bar-chart",
    "calendar",
    "person",
]


def to_camel(name: str) -> str:
    parts = name.split("-")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def main() -> None:
    url = "https://registry.npmjs.org/@expo/vector-icons/-/vector-icons-15.0.2.tgz"
    with urllib.request.urlopen(url, timeout=30) as resp:
        archive_bytes = resp.read()

    with tarfile.open(fileobj=io.BytesIO(archive_bytes), mode="r:gz") as tf:
        glyph_member = next(
            m for m in tf.getmembers() if m.name.endswith("glyphmaps/Ionicons.json")
        )
        ttf_member = next(
            m for m in tf.getmembers() if m.name.endswith("Fonts/Ionicons.ttf")
        )
        glyphs = json.loads(tf.extractfile(glyph_member).read().decode("utf-8"))
        ttf_bytes = tf.extractfile(ttf_member).read()

    os.makedirs(os.path.dirname(TTF_OUT), exist_ok=True)
    with open(TTF_OUT, "wb") as fp:
        fp.write(ttf_bytes)

    os.makedirs(os.path.dirname(DART_OUT), exist_ok=True)
    lines = [
        "// GENERATED BY tool/extract_ionicons.py — DO NOT EDIT MANUALLY.",
        "import 'package:flutter/widgets.dart';",
        "",
        "class KarsaIcons {",
        "  KarsaIcons._();",
        "",
        "  static const String fontFamily = 'Ionicons';",
        "",
    ]
    for name in ICON_NAMES:
        code = glyphs[name]
        prop = to_camel(name)
        lines.append(
            f"  static const IconData {prop} = IconData(0x{code:04x}, fontFamily: fontFamily);"
        )

    lines.append("")
    lines.append("  static const Map<String, IconData> byName = <String, IconData>{")
    for name in ICON_NAMES:
        prop = to_camel(name)
        lines.append(f"    '{name}': {prop},")
    lines.append("  };")
    lines.append("")
    lines.append("  static IconData resolve(String name) {")
    lines.append("    return byName[name] ?? helpCircleOutline;")
    lines.append("  }")
    lines.append("}")
    lines.append("")

    with open(DART_OUT, "w", encoding="utf-8") as fp:
        fp.write("\n".join(lines))

    print(f"Wrote {TTF_OUT} ({len(ttf_bytes)} bytes) and {DART_OUT} ({len(ICON_NAMES)} icons).")


if __name__ == "__main__":
    main()
